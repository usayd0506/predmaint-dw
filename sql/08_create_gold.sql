USE PredMaintDW;
GO

SELECT TABLE_NAME
FROM INFORMATION_SCHEMA.TABLES
WHERE TABLE_SCHEMA = 'gold';

/*
Table	                        Purpose
gold.run_control	            Tracks which source batch produced the Gold results
gold.engine_health	            Stores health scores and risk classifications
gold.ml_predictions	            Stores predicted RUL and failure probabilities
gold.model_metrics	            Stores model accuracy and scheduling metrics
gold.risk_thresholds	        Stores configurable critical/warning thresholds
gold.rule_catalog	            Stores the expert-system rules
gold.alerts	                    Stores alerts generated by those rules
gold.work_order_schedule	    Stores GA and greedy technician assignments
*/



CREATE TABLE gold.engine_health (
    engine_uid INT PRIMARY KEY,
    plant_id INT NOT NULL,
    cycles_run INT NOT NULL,
    last_cycle_date DATE NOT NULL,
    last_maintenance DATE NULL,
    health_index DECIMAL(5,2) NOT NULL,
    degradation_stage VARCHAR(10) NOT NULL,
    risk_level VARCHAR(10) NOT NULL,
    run_id UNIQUEIDENTIFIER NOT NULL
);


CREATE TABLE gold.ml_predictions (
    engine_uid INT NOT NULL,
    model_name VARCHAR(50) NOT NULL,
    predicted_rul FLOAT NOT NULL,
    failure_prob_30 FLOAT NOT NULL,
    run_id UNIQUEIDENTIFIER NOT NULL,
    predicted_at DATETIME2 DEFAULT SYSDATETIME(),
    PRIMARY KEY (engine_uid, model_name, run_id)
);

CREATE TABLE gold.model_metrics (
        run_id UNIQUEIDENTIFIER NOT NULL,
        model_name VARCHAR(50) NOT NULL,
        metric VARCHAR(50) NOT NULL,
        value FLOAT NOT NULL,
        CONSTRAINT PK_gold_metrics PRIMARY KEY (run_id, model_name, metric)
    );

CREATE TABLE gold.run_control (
     run_id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY,
     bronze_batch_id UNIQUEIDENTIFIER NOT NULL,
     source_version VARCHAR(100) NOT NULL,
     created_at DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
     status VARCHAR(20) NOT NULL,
     CONSTRAINT UQ_gold_source_version UNIQUE (source_version)
    );
/*
Critical risk:
An engine is Critical when:
•	Predicted RUL is less than 30 cycles, OR
•	Failure probability is greater than 0.70 (70%).
Warning risk:
If the engine isn't Critical, it is Warning when:
•	Predicted RUL is less than 60 cycles, OR
•	Failure probability is greater than 0.40 (40%).
Otherwise, the engine is Healthy.
*/


CREATE TABLE gold.risk_thresholds (
     threshold_id INT NOT NULL PRIMARY KEY,
     critical_rul FLOAT NOT NULL,
     critical_probability FLOAT NOT NULL,
     warning_rul FLOAT NOT NULL,
     warning_probability FLOAT NOT NULL
    );
INSERT INTO gold.risk_thresholds VALUES (1, 30, 0.70, 60, 0.40);

CREATE TABLE gold.rule_catalog (
     rule_id VARCHAR(5) NOT NULL PRIMARY KEY,
     description VARCHAR(200) NOT NULL,
     severity VARCHAR(10) NOT NULL,
     action VARCHAR(100) NOT NULL
    );
