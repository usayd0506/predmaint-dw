CREATE TABLE gold.alerts (
     alert_id INT IDENTITY(1,1) PRIMARY KEY,
     engine_uid INT NOT NULL,
     severity VARCHAR(10) NOT NULL,
     action VARCHAR(100) NOT NULL,
     rules_fired VARCHAR(300) NOT NULL,
     run_id UNIQUEIDENTIFIER NOT NULL,
     created_at DATETIME2 NOT NULL DEFAULT SYSDATETIME()
   );

CREATE TABLE gold.work_order_schedule (
     schedule_id INT IDENTITY(1,1) PRIMARY KEY,
     engine_uid INT NOT NULL,
     technician_id INT NOT NULL,
     slot_start DATETIME2 NOT NULL,
     slot_hours DECIMAL(5,1) NOT NULL,
     method VARCHAR(10) NOT NULL,
     est_cost DECIMAL(12,2) NOT NULL,
     run_id UNIQUEIDENTIFIER NOT NULL,
     CONSTRAINT CK_gold_schedule_method CHECK (method IN ('GA', 'GREEDY')),
     CONSTRAINT UQ_gold_schedule UNIQUE (run_id, method, engine_uid),
     CONSTRAINT UQ_gold_technician_slot UNIQUE (run_id, method, technician_id, slot_start)
   );

SELECT TABLE_NAME FROM INFORMATION_SCHEMA.TABLES
WHERE TABLE_SCHEMA = 'gold' ORDER BY TABLE_NAME;